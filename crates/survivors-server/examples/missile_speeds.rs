//! Print `crates/survivors-sim/src/speeds.rs`: the missile speed of every spell the survivors mode casts, from the
//! client's `Spell.dbc`, so the dedicated server times its hits as a solo run does without the
//! game data. `cargo run -p survivors-server --example missile_speeds -- wow-data/Data`.

use survivors_sim::data;

fn main() {
    let dir = std::env::args().nth(1).expect("usage: missile_speeds <WoW Data dir>");
    let mut chain = benilla_formats::Chain::open(std::path::Path::new(&dir)).expect("patch chain");
    let catalog = benilla_formats::load_spell_catalog(&mut chain).expect("Spell.dbc");
    let mut spells: Vec<u32> = data::ABILITIES
        .iter()
        .flat_map(|a| [a.spell, a.totem.1])
        .filter(|&s| s != 0)
        .collect();
    spells.sort_unstable();
    spells.dedup();
    println!("//! Missile speeds (yd/s) of the spells the mode casts, from `Spell.dbc` column 37.");
    println!("//! Generated by `cargo run -p survivors-server --example missile_speeds -- <Data>`.");
    println!();
    println!("pub const MISSILE_SPEEDS: &[(u32, f32)] = &[");
    for s in spells {
        let speed = catalog.get(s).map_or(0.0, |d| d.speed);
        if speed > 0.0 {
            println!("    ({s}, {speed:?}),");
        }
    }
    println!("];");
}
